"""Create the standalone Big O candidate from the closed local proof sources."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parent
modules = []
seen = set()
external_imports = []

def visit(name):
    if name in seen:
        return
    seen.add(name)
    path = ROOT / (name.replace('.', '/') + '.lean')
    if name == 'BigOStatement':
        path = ROOT / 'Platform/bigo_Statement.lean'
    source = path.read_text(encoding='utf8')
    lines = []
    for line in source.splitlines():
        if line.startswith('import '):
            for imported in line.removeprefix('import ').split():
                if imported.startswith('Mathlib'):
                    if imported not in external_imports:
                        external_imports.append(imported)
                else:
                    assert (ROOT / (imported.replace('.', '/') + '.lean')).is_file(), imported
                    visit(imported)
        else:
            lines.append(line)
    modules.append((name, path.relative_to(ROOT).as_posix(), '\n'.join(lines).strip()))

visit('AverageSensitivity.WallisAssembly')
visit('BigOStatement')
header = '''/-
Standalone candidate for Big O Speedrun's proposed average-sensitivity target.
Exact coefficient: 399/125 (3.192). Entry point: Race.bound.
This file is generated by prepare_bigo.py from the closed source modules.

The OAI construction and model are authored by OpenAI, openai/math commit
1581d4cbdd69a0faf34b2089614fe2a814316a6a, Apache-2.0, with the recorded
Lean 4.33.1 compatibility changes. The coupling refinement is credited to
Prathmesh Lagdive, Vaibhav Aglave and Suraj Damre, manuscript/code revision
5e9f26cf74935f08be20f9ac4deb57b291d707d8. The new proofs, integration,
constant extraction and target adapter are published by Anchen0823 under
Apache-2.0 with OpenAI Codex assistance. See LICENSE and NOTICE in this repo.

The proposed trusted statement still requires maintainer review and enabling.
This file does not itself establish Big O's Lean Verified evidence label.
-/
'''
body = [header, '\n'.join('import ' + name for name in external_imports)]
for name, path, source in modules:
    body.append(f'/- Begin source module {name} ({path}). -/\n{source}\n'
                f'/- End source module {name}. -/')
body.append('''namespace Race

theorem bound : BigOSpeedrun.AverageSensitivity.Bound (399/125 : ℚ) := by
  intro n d hn hd _ p hdegree
  convert _root_.AverageSensitivity.AS_bound_399_125 hn hd p hdegree using 1 <;>
    norm_num

end Race

/-- info: 'Race.bound' depends on axioms: [propext, Classical.choice, Quot.sound] -/
#guard_msgs in
#print axioms Race.bound
''')
output = ROOT / 'Submission.lean'
output.write_text('\n\n'.join(body), encoding='utf8', newline='\n')
record = {
    'entry_point': 'Race.bound',
    'target': 'BigOSpeedrun.AverageSensitivity.Bound (399/125 : ℚ)',
    'bound': '399/125',
    'status': 'candidate-for-proposed-target-not-yet-enabled-by-Big-O',
    'modules': [{'name': n, 'path': p} for n, p, _ in modules],
    'imports': external_imports,
    'sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
    'byte_count': output.stat().st_size,
    'toolchain': 'leanprover/lean4:v4.33.1',
    'mathlib': '0df444a360eaa60ab8c11dca51a86af692955474',
}
(ROOT / 'Verification/bigo_candidate.json').write_text(
    json.dumps(record, indent=2) + '\n', encoding='utf8')
print(f'Generated {output.name}: {len(modules)} source modules, {output.stat().st_size} bytes')
